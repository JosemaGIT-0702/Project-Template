"""Numerical results shared between calculations and the paper.

Every script writes results/<script-name>.json with entries

    {"SigmaTot": {"value": 868.5, "digits": 4, "unit": "pb"}, ...}

and `make values` (python -m hepcalc.results) turns all of them into
paper/generated/values.tex, defining \\valSigmaTot etc. Numbers in the paper
must come from these macros, never be typed by hand.
"""

import json
import re
from pathlib import Path

from .paths import GENERATED, RESULTS


def export_values(name: str, values: dict) -> Path:
    """Write results/<name>.json. Values may be floats or dicts with value/digits/unit."""
    RESULTS.mkdir(parents=True, exist_ok=True)
    out = {k: v if isinstance(v, dict) else {"value": float(v)} for k, v in values.items()}
    path = RESULTS / f"{name}.json"
    path.write_text(json.dumps(out, indent=2) + "\n")
    return path


def _fmt(entry: dict) -> str:
    value = entry["value"]
    digits = entry.get("digits", 4)
    text = f"{value:.{digits}g}"
    if "e" in text:
        mant, exp = text.split("e")
        text = rf"{mant}\times 10^{{{int(exp)}}}"
    if unit := entry.get("unit"):
        text += rf"\,\mathrm{{{unit}}}"
    return text


def build_values_tex() -> Path:
    """Collect every results/*.json into paper/generated/values.tex."""
    lines = ["% generated by `make values` -- do not edit", ""]
    seen: dict[str, str] = {}
    for path in sorted(RESULTS.glob("*.json")):
        for key, entry in json.loads(path.read_text()).items():
            if not re.fullmatch(r"[A-Za-z]+", key):
                raise ValueError(f"{path.name}: key {key!r} must be letters only (LaTeX macro)")
            if key in seen:
                raise ValueError(f"duplicate key {key!r} in {path.name} and {seen[key]}")
            seen[key] = path.name
            lines.append(rf"\newcommand{{\val{key}}}{{\ensuremath{{{_fmt(entry)}}}}}  % {path.name}")
    GENERATED.mkdir(parents=True, exist_ok=True)
    out = GENERATED / "values.tex"
    out.write_text("\n".join(lines) + "\n")
    return out


if __name__ == "__main__":
    print(f"wrote {build_values_tex()}")
